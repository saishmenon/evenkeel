/**
 * npm run build:tokens
 * Generates everything from the theme presets + foundations:
 *   build/css/themes.css       palettes per theme       (Figma: Primitives + Theme collections)
 *   build/css/roles.css        colour roles, light/dark (Figma: Color collection)
 *   build/css/foundations.css  space, radius, density, type, depth, motion
 *   build/css/palettes.css     spectrum, greys, system and data-viz palettes (--ek-*)
 *   build/css/evenkeel.css        imports all of the above (the one file apps import)
 *   build/tokens.json          the same data, shaped for the Figma sync
 *   build/figma/palettes.json  palettes only, light/dark arrays, for Figma variables
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { presets, hues, status, type PresetName } from '../src/theme/presets';
import { buildTheme, buildStatus } from '../src/theme/palette';
import { paletteVars, roleVars, cssName } from '../src/theme/css';
import { roles } from '../src/theme/roles';
import { paletteStaticVars, paletteModeVars, palettesJson, spectrum, type SpectrumHue } from '../src/theme/palettes';
import { space, radius, density, textStyles, elevation, materialBlur, motion } from '../src/tokens/foundations';

const HEADER = '/* Generated by scripts/build.ts. Do not edit by hand. */\n';
const block = (selector: string, vars: Record<string, string>) =>
  `${selector} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;

mkdirSync('build/css', { recursive: true });

// ---------- themes.css ----------
const statusPal = buildStatus();
const statusVars: Record<string, string> = {};
for (const [hue, modes] of Object.entries(statusPal)) {
  for (const mode of ['light', 'dark'] as const) {
    modes[mode].scale.forEach((hex, i) => (statusVars[`--palette-${hue}-${mode}-${i + 1}`] = hex));
    statusVars[`--palette-${hue}-on-${mode}`] = modes[mode].on;
  }
}
const themes = Object.fromEntries(Object.entries(presets).map(([name, cfg]) => [name, buildTheme(cfg)])) as Record<PresetName, ReturnType<typeof buildTheme>>;
let themesCss = HEADER + '\n/* Status hues: the same in every theme */\n' + block(':root', statusVars);
for (const [name, pal] of Object.entries(themes)) {
  const selector = name === 'default' ? `:root, [data-theme="default"]` : `[data-theme="${name}"]`;
  themesCss += `\n/* Theme: ${name} */\n` + block(selector, paletteVars(pal));
}
writeFileSync('build/css/themes.css', themesCss);

// ---------- roles.css ----------
// Each role holds BOTH values: light-dark(light, dark).
// The browser picks one from the element's color-scheme, which inherits.
// Roles are re-declared on every [data-theme] and [data-mode], so themes AND modes can nest freely
// (browsers resolve light-dark() where a custom property is declared, so a dark island must re-declare them)
// (a Studio-themed card inside a Default-themed page just works).
const light = roleVars('light');
const dark = roleVars('dark');
const both = Object.fromEntries(Object.keys(light).map((k) => [k, `light-dark(${light[k]}, ${dark[k]})`]));
const rolesCss = HEADER +
  '\n/* Mode: follows the OS by default; data-mode forces one */\n' +
  block(':root', { 'color-scheme': 'light dark' }) +
  block('[data-mode="light"]', { 'color-scheme': 'light' }) +
  block('[data-mode="dark"]', { 'color-scheme': 'dark' }) +
  '\n/* Colour roles */\n' + block(':root, [data-theme], [data-mode]', both);
writeFileSync('build/css/roles.css', rolesCss);

// ---------- foundations.css ----------
const px = (n: number) => `${n}px`;
const f: Record<string, string> = {};
for (const [k, v] of Object.entries(space)) f[`--space-${k.replace('.', '_')}`] = px(v);
for (const [k, v] of Object.entries(radius)) f[`--radius-${k}`] = px(v);
for (const [k, v] of Object.entries(motion.duration)) f[`--duration-${k}`] = `${v}ms`;
for (const [k, v] of Object.entries(motion.easing)) f[`--easing-${k}`] = v;
for (const [k, v] of Object.entries(materialBlur)) f[`--blur-material-${k}`] = px(v);
for (const [lvl, layers] of Object.entries(elevation)) {
  f[`--elevation-${lvl}`] = layers
    .map((l) => `0 ${l.y}px ${l.blur}px ${l.spread}px color-mix(in srgb, var(--color-shadow-color) ${Math.round(l.alpha * 100)}%, transparent)`)
    .join(', ');
}
const densityVars = (d: 'comfortable' | 'compact') =>
  Object.fromEntries(Object.entries(density).map(([k, v]) => [`--${cssName(k)}`, `var(--space-${v[d].replace('.', '_')})`]));

let textCss = '';
for (const [name, t] of Object.entries(textStyles)) {
  textCss += `/* ${t.description} */\n.text-${name} {\n  font-family: var(--font-${t.font});\n  font-size: ${t.size}px;\n  line-height: ${t.line}px;\n  font-weight: ${t.weight};\n  letter-spacing: ${t.tracking / 100}em;\n}\n`;
}
const foundationsCss = HEADER + '\n' + block(':root', f) +
  '\n/* Density: comfortable by default */\n' + block(':root, [data-density="comfortable"]', densityVars('comfortable')) +
  block('[data-density="compact"]', densityVars('compact')) +
  '\n/* Text styles (named roles, sized for web) */\n' + textCss;
writeFileSync('build/css/foundations.css', foundationsCss);

// ---------- palettes.css ----------
// Static hex per mode on :root; the switching names (--ek-blue-9) use light-dark() and are
// re-declared wherever theme or mode can change, exactly like the roles.
const palStatic = paletteStaticVars();
const palMode = paletteModeVars();
const palettesCss = HEADER +
  '\n/* Palettes: fixed values per mode (--ek-<hue>-light-<step>, --ek-<hue>-dark-<step>, --ek-viz-cat-light-1 …) */\n' + block(':root', palStatic) +
  '\n/* Palettes that follow the mode: --ek-<hue>-<step>, --ek-viz-cat-<n>, --ek-success-subtle … */\n' + block(':root, [data-theme], [data-mode]', palMode);
writeFileSync('build/css/palettes.css', palettesCss);

writeFileSync('build/css/evenkeel.css', HEADER + `@import './themes.css';\n@import './roles.css';\n@import './palettes.css';\n@import './foundations.css';\n`);

// ---------- tokens.json (for Figma) ----------
const primitives: Record<string, string> = { white: '#ffffff', black: '#000000' };
// accent hues used by presets + status hues, generated per mode
const usedHues = new Set<string>([...Object.values(status)]);
for (const cfg of Object.values(presets)) {
  const hue = Object.entries(hues).find(([, v]) => v.light === cfg.accent.light)?.[0];
  if (hue) usedHues.add(hue);
}
for (const hue of usedHues) {
  for (const mode of ['light', 'dark'] as const) {
    const s = statusPal[hue]?.[mode].scale ?? buildTheme({ ...presets.default, accent: (hues as any)[hue] })[mode].accent;
    s.forEach((hex, i) => (primitives[`${hue}/${mode}/${i + 1}`] = hex));
  }
}
// spectrum hues referenced directly by roles (violet for ai/*): same in every theme
const roleHues = new Set(roles.flatMap((r) => [r.light, r.dark]).map((ref) => ref.split('.')[0]).filter((h) => h in spectrum && !statusPal[h]));
for (const hue of roleHues) {
  for (const mode of ['light', 'dark'] as const) spectrum[hue as SpectrumHue][mode].scale.forEach((hex, i) => (primitives[`${hue}/${mode}/${i + 1}`] = hex));
}
const neutralNames = ['slate', 'gray', 'sand'] as const;
for (const n of neutralNames) {
  const pal = buildTheme({ ...presets.default, neutral: n });
  for (const mode of ['light', 'dark'] as const) {
    pal[mode].neutral.forEach((hex, i) => (primitives[`${n}/${mode}/${i + 1}`] = hex));
    pal[mode].neutralA.forEach((hex, i) => (primitives[`${n}-alpha/${mode}/${i + 1}`] = hex));
    for (const [k, hex] of Object.entries(pal[mode].material)) primitives[`${n}-material/${mode}/${k}`] = hex;
  }
}
const themeModes = Object.fromEntries(Object.entries(presets).map(([name, cfg]) => {
  const hue = Object.entries(hues).find(([, v]) => v.light === cfg.accent.light)![0];
  return [name, { accent: hue, neutral: cfg.neutral, onAccent: { light: themes[name as PresetName].light.onAccent, dark: themes[name as PresetName].dark.onAccent }, radius: themes[name as PresetName].radius, font: themes[name as PresetName].font }];
}));
const statusOn = Object.fromEntries(Object.entries(statusPal).map(([h, m]) => [h, { light: m.light.on, dark: m.dark.on }]));
const palettes = palettesJson();
writeFileSync('build/tokens.json', JSON.stringify({ primitives, themeModes, statusOn, roles, space, radius, density, textStyles, elevation, materialBlur, motion, palettes }, null, 1));
mkdirSync('build/figma', { recursive: true });
writeFileSync('build/figma/palettes.json', JSON.stringify(palettes, null, 1));

console.log(`themes: ${Object.keys(presets).length} · roles: ${roles.length} · primitives (Figma): ${Object.keys(primitives).length} · text styles: ${Object.keys(textStyles).length}`);
console.log(`palettes: ${Object.keys(palStatic).length} fixed + ${Object.keys(palMode).length} mode-switching CSS vars · ${Object.keys(palettes.spectrum).length} hues × 12 · ${palettes.viz.categorical.light.length} categorical · ${Object.keys(palettes.system).length} system colours → build/figma/palettes.json`);
